import 'dart:ui';
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import '../providers/add_school_provider.dart';

/// Écran "Ajouter une école" réservé au Super Administrateur
/// Respecte la charte graphique : Glassmorphisme, accents argent & or, Poppins & Inter
class AddSchoolScreen extends ConsumerStatefulWidget {
  const AddSchoolScreen({Key? key}) : super(key: key);

  static const String routeName = '/admin/add-school';

  @override
  ConsumerState<AddSchoolScreen> createState() => _AddSchoolScreenState();
}

class _AddSchoolScreenState extends ConsumerState<AddSchoolScreen> {
  final _formKey = GlobalKey<FormState>();

  final _schoolNameController = TextEditingController();
  final _slugController = TextEditingController();
  final _adminNameController = TextEditingController();
  final _adminEmailController = TextEditingController();
  final _tempPasswordController = TextEditingController();

  bool _obscurePassword = true;

  @override
  void dispose() {
    _schoolNameController.dispose();
    _slugController.dispose();
    _adminNameController.dispose();
    _adminEmailController.dispose();
    _tempPasswordController.dispose();
    super.dispose();
  }

  /// Génération automatique du slug lors de la saisie du nom de l'école
  void _onSchoolNameChanged(String value) {
    if (_slugController.text.isEmpty || _isAutoGeneratedSlug(_slugController.text)) {
      final generated = value
          .toLowerCase()
          .trim()
          .replaceAll(RegExp(r'[\s_]+'), '-')
          .replaceAll(RegExp(r'[^a-z0-9-]'), '');
      _slugController.text = generated;
    }
  }

  bool _isAutoGeneratedSlug(String current) {
    return current.isEmpty || current.endsWith('-');
  }

  void _submitForm() {
    if (!_formKey.currentState!.validate()) return;

    ref.read(addSchoolProvider.notifier).createSchool(
      schoolName: _schoolNameController.text,
      slug: _slugController.text,
      adminName: _adminNameController.text,
      adminEmail: _adminEmailController.text,
      tempPassword: _tempPasswordController.text,
    );
  }

  void _resetForm() {
    _schoolNameController.clear();
    _slugController.clear();
    _adminNameController.clear();
    _adminEmailController.clear();
    _tempPasswordController.clear();
    ref.read(addSchoolProvider.notifier).reset();
  }

  @override
  Widget build(BuildContext context) {
    final state = ref.watch(addSchoolProvider);
    final isDarkMode = Theme.of(context).brightness == Brightness.dark;

    // Palette selon le document docs/03-design.md
    final goldAccent = isDarkMode ? const Color(0xFFE5C158) : const Color(0xFFD4AF37);
    final silverBorder = isDarkMode ? const Color(0xFF475569) : const Color(0xFFCBD5E1);
    final cardBg = isDarkMode 
        ? Colors.black.withOpacity(0.35) 
        : Colors.white.withOpacity(0.12);

    return Scaffold(
      body: Container(
        width: double.infinity,
        height: double.infinity,
        decoration: BoxDecoration(
          gradient: LinearGradient(
            colors: isDarkMode
                ? const [Color(0xFF0B1220), Color(0xFF1E1B4B), Color(0xFF2E1065)]
                : const [Color(0xFF1E3A8A), Color(0xFF4C1D95), Color(0xFF6D28D9)],
            begin: Alignment.topLeft,
            end: Alignment.bottomRight,
          ),
        ),
        child: SafeArea(
          child: Center(
            child: SingleChildScrollView(
              padding: const EdgeInsets.symmetric(horizontal: 20.0, vertical: 24.0),
              child: ConstrainedBox(
                constraints: const BoxConstraints(maxWidth: 680),
                child: ClipRRect(
                  borderRadius: BorderRadius.circular(24.0),
                  child: BackdropFilter(
                    filter: ImageFilter.blur(sigmaX: 16.0, sigmaY: 16.0),
                    child: Container(
                      decoration: BoxDecoration(
                        color: cardBg,
                        borderRadius: BorderRadius.circular(24.0),
                        border: Border.all(color: silverBorder.withOpacity(0.35), width: 1.2),
                        boxShadow: [
                          BoxShadow(
                            color: Colors.black.withOpacity(0.25),
                            blurRadius: 30,
                            offset: const Offset(0, 15),
                          )
                        ],
                      ),
                      padding: const EdgeInsets.all(28.0),
                      child: state.successResult != null
                          ? _buildSuccessView(state.successResult!, goldAccent)
                          : _buildFormView(state, goldAccent, silverBorder),
                    ),
                  ),
                ),
              ),
            ),
          ),
        ),
      ),
    );
  }

  /// Vue du formulaire de saisie
  Widget _buildFormView(AddSchoolState state, Color goldAccent, Color silverBorder) {
    return Form(
      key: _formKey,
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        mainAxisSize: MainAxisSize.min,
        children: [
          // En-tête de page
          Row(
            children: [
              Container(
                padding: const EdgeInsets.all(12),
                decoration: BoxDecoration(
                  color: goldAccent.withOpacity(0.15),
                  borderRadius: BorderRadius.circular(16),
                  border: Border.all(color: goldAccent.withOpacity(0.3)),
                ),
                child: Icon(Icons.domain_add_rounded, color: goldAccent, size: 28),
              ),
              const SizedBox(width: 16),
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    const Text(
                      'Créer un nouveau tenant (École)',
                      style: TextStyle(
                        fontFamily: 'Poppins',
                        fontSize: 22,
                        fontWeight: FontWeight.bold,
                        color: Colors.white,
                      ),
                    ),
                    const SizedBox(height: 4),
                    Text(
                      'Réservé au Super Administrateur • Isolation RLS stricte',
                      style: TextStyle(
                        fontFamily: 'Inter',
                        fontSize: 13,
                        color: Colors.white.withOpacity(0.7),
                      ),
                    ),
                  ],
                ),
              ),
            ],
          ),
          const SizedBox(height: 24),
          Divider(color: silverBorder.withOpacity(0.25)),
          const SizedBox(height: 16),

          // Message d'erreur
          if (state.errorMessage != null) ...[
            Container(
              padding: const EdgeInsets.all(14),
              decoration: BoxDecoration(
                color: const Color(0xFFDC2626).withOpacity(0.2),
                borderRadius: BorderRadius.circular(14),
                border: Border.all(color: const Color(0xFFDC2626).withOpacity(0.5)),
              ),
              child: Row(
                children: [
                  const Icon(Icons.error_outline_rounded, color: Color(0xFFFCA5A5), size: 22),
                  const SizedBox(width: 12),
                  Expanded(
                    child: Text(
                      state.errorMessage!,
                      style: const TextStyle(
                        fontFamily: 'Inter',
                        color: Color(0xFFFEE2E2),
                        fontSize: 13,
                        fontWeight: FontWeight.w500,
                      ),
                    ),
                  ),
                ],
              ),
            ),
            const SizedBox(height: 20),
          ],

          // Champ 1: Nom de l'école
          _buildLabel('Nom officiel de l\'établissement *'),
          TextFormField(
            controller: _schoolNameController,
            onChanged: _onSchoolNameChanged,
            style: const TextStyle(color: Colors.white, fontFamily: 'Inter'),
            decoration: _inputDecoration(
              hint: 'ex: Collège Frère Zuza',
              icon: Icons.school_outlined,
              silverBorder: silverBorder,
            ),
            validator: (val) {
              if (val == null || val.trim().isEmpty) {
                return 'Le nom de l\'école est obligatoire.';
              }
              return null;
            },
          ),
          const SizedBox(height: 18),

          // Champ 2: Code école / Slug
          _buildLabel('Code école / Slug (Unique, minuscules, sans espaces) *'),
          TextFormField(
            controller: _slugController,
            inputFormatters: [
              FilteringTextInputFormatter.allow(RegExp(r'[a-z0-9-]')),
            ],
            style: TextStyle(
              color: goldAccent, 
              fontFamily: 'Inter', 
              fontWeight: FontWeight.w600,
              letterSpacing: 0.5,
            ),
            decoration: _inputDecoration(
              hint: 'ex: zuza-kinshasa',
              icon: Icons.tag_rounded,
              silverBorder: silverBorder,
              helper: 'Utilisé par le personnel pour se connecter à l\'application.',
            ),
            validator: (val) {
              if (val == null || val.trim().isEmpty) {
                return 'Le code école / slug est obligatoire.';
              }
              final regex = RegExp(r'^[a-z0-9-]+$');
              if (!regex.hasMatch(val.trim())) {
                return 'Minuscules, chiffres et tirets uniquement (sans espaces).';
              }
              return null;
            },
          ),
          const SizedBox(height: 22),

          // Sous-titre Administrateur
          Text(
            'Administrateur initial (Rôle Préfet)',
            style: TextStyle(
              fontFamily: 'Poppins',
              fontSize: 15,
              fontWeight: FontWeight.w600,
              color: goldAccent,
            ),
          ),
          const SizedBox(height: 14),

          // Champ 3: Nom complet de l'administrateur
          _buildLabel('Nom complet de l\'administrateur (Préfet) *'),
          TextFormField(
            controller: _adminNameController,
            style: const TextStyle(color: Colors.white, fontFamily: 'Inter'),
            decoration: _inputDecoration(
              hint: 'ex: Rév. Père Jean-Baptiste Makengo',
              icon: Icons.person_outline_rounded,
              silverBorder: silverBorder,
            ),
            validator: (val) {
              if (val == null || val.trim().isEmpty) {
                return 'Le nom de l\'administrateur est obligatoire.';
              }
              return null;
            },
          ),
          const SizedBox(height: 18),

          // Champ 4: Email de l'administrateur
          _buildLabel('Adresse email professionnelle de l\'administrateur *'),
          TextFormField(
            controller: _adminEmailController,
            keyboardType: TextInputType.emailAddress,
            style: const TextStyle(color: Colors.white, fontFamily: 'Inter'),
            decoration: _inputDecoration(
              hint: 'ex: direction@zuza.cd',
              icon: Icons.email_outlined,
              silverBorder: silverBorder,
            ),
            validator: (val) {
              if (val == null || val.trim().isEmpty) {
                return 'L\'email est obligatoire.';
              }
              final emailRegex = RegExp(r'^[^\s@]+@[^\s@]+\.[^\s@]+$');
              if (!emailRegex.hasMatch(val.trim())) {
                return 'Veuillez saisir une adresse email valide.';
              }
              return null;
            },
          ),
          const SizedBox(height: 18),

          // Champ 5: Mot de passe temporaire
          _buildLabel('Mot de passe temporaire (min 8 caractères) *'),
          TextFormField(
            controller: _tempPasswordController,
            obscureText: _obscurePassword,
            style: const TextStyle(color: Colors.white, fontFamily: 'Inter'),
            decoration: _inputDecoration(
              hint: '••••••••••••',
              icon: Icons.lock_outline_rounded,
              silverBorder: silverBorder,
              suffix: IconButton(
                icon: Icon(
                  _obscurePassword ? Icons.visibility_outlined : Icons.visibility_off_outlined,
                  color: Colors.white70,
                  size: 20,
                ),
                onPressed: () => setState(() => _obscurePassword = !_obscurePassword),
              ),
            ),
            validator: (val) {
              if (val == null || val.length < 8) {
                return 'Le mot de passe doit comporter au moins 8 caractères.';
              }
              return null;
            },
          ),
          const SizedBox(height: 28),

          // Bouton d'action Soumettre
          SizedBox(
            width: double.infinity,
            height: 52,
            child: ElevatedButton(
              onPressed: state.isLoading ? null : _submitForm,
              style: ElevatedButton.styleFrom(
                backgroundColor: goldAccent,
                foregroundColor: const Color(0xFF0F172A),
                elevation: 4,
                shape: RoundedRectangleBorder(
                  borderRadius: BorderRadius.circular(16.0),
                ),
              ),
              child: state.isLoading
                  ? const SizedBox(
                      width: 24,
                      height: 24,
                      child: CircularProgressIndicator(
                        strokeWidth: 2.5,
                        valueColor: AlwaysStoppedAnimation<Color>(Color(0xFF0F172A)),
                      ),
                    )
                  : const Row(
                      mainAxisAlignment: MainAxisAlignment.center,
                      children: [
                        Icon(Icons.add_business_rounded, size: 20),
                        SizedBox(width: 10),
                        Text(
                          'Créer l\'école et son compte administrateur',
                          style: TextStyle(
                            fontFamily: 'Inter',
                            fontWeight: FontWeight.bold,
                            fontSize: 15,
                          ),
                        ),
                      ],
                    ),
            ),
          ),
        ],
      ),
    );
  }

  /// Vue affichée après succès de la création
  Widget _buildSuccessView(CreatedSchoolResult result, Color goldAccent) {
    return Column(
      mainAxisSize: MainAxisSize.min,
      crossAxisAlignment: CrossAxisAlignment.center,
      children: [
        Container(
          width: 68,
          height: 68,
          decoration: BoxDecoration(
            color: const Color(0xFF16A34A).withOpacity(0.2),
            shape: BoxShape.circle,
            border: Border.all(color: const Color(0xFF16A34A), width: 2),
          ),
          child: const Icon(Icons.check_rounded, color: Color(0xFF4ADE80), size: 40),
        ),
        const SizedBox(height: 18),
        Text(
          'École créée avec succès !',
          textAlign: TextAlign.center,
          style: const TextStyle(
            fontFamily: 'Poppins',
            fontSize: 22,
            fontWeight: FontWeight.bold,
            color: Colors.white,
          ),
        ),
        const SizedBox(height: 8),
        Text(
          'L\'établissement a été isolé et sécurisé dans la base multi-tenant Supabase.',
          textAlign: TextAlign.center,
          style: TextStyle(
            fontFamily: 'Inter',
            fontSize: 13,
            color: Colors.white.withOpacity(0.75),
          ),
        ),
        const SizedBox(height: 24),

        // Carte récapitulative des identifiants à transmettre
        Container(
          width: double.infinity,
          padding: const EdgeInsets.all(20),
          decoration: BoxDecoration(
            color: Colors.black.withOpacity(0.4),
            borderRadius: BorderRadius.circular(18),
            border: Border.all(color: goldAccent.withOpacity(0.4)),
          ),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              _buildCredentialRow('Nom de l\'école :', result.schoolName),
              const SizedBox(height: 12),
              _buildCredentialRow('Code école (Slug à communiquer) :', result.schoolCode, isHighlight: true, goldAccent: goldAccent),
              const SizedBox(height: 12),
              _buildCredentialRow('Email administrateur :', result.adminEmail),
              const SizedBox(height: 12),
              _buildCredentialRow('Rôle attribué :', 'Préfet des études (Admin d\'école)'),
            ],
          ),
        ),
        const SizedBox(height: 24),

        // Boutons : Copier le code école & Créer une autre école
        Row(
          children: [
            Expanded(
              child: OutlinedButton.icon(
                onPressed: () {
                  Clipboard.setData(ClipboardData(text: result.schoolCode));
                  ScaffoldMessenger.of(context).showSnackBar(
                    const SnackBar(content: Text('Code école copié dans le presse-papier.')),
                  );
                },
                icon: const Icon(Icons.copy_rounded, size: 18),
                label: const Text('Copier le code école'),
                style: OutlinedButton.styleFrom(
                  foregroundColor: Colors.white,
                  side: BorderSide(color: Colors.white.withOpacity(0.4)),
                  padding: const EdgeInsets.symmetric(vertical: 14),
                  shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(14)),
                ),
              ),
            ),
            const SizedBox(width: 14),
            Expanded(
              child: ElevatedButton.icon(
                onPressed: _resetForm,
                icon: const Icon(Icons.add_rounded, size: 18),
                label: const Text('Ajouter une autre école'),
                style: ElevatedButton.styleFrom(
                  backgroundColor: goldAccent,
                  foregroundColor: const Color(0xFF0F172A),
                  padding: const EdgeInsets.symmetric(vertical: 14),
                  shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(14)),
                ),
              ),
            ),
          ],
        ),
      ],
    );
  }

  Widget _buildCredentialRow(String label, String value, {bool isHighlight = false, Color? goldAccent}) {
    return Row(
      crossAxisAlignment: CrossAxisAlignment.start,
      mainAxisAlignment: MainAxisAlignment.between,
      children: [
        Text(
          label,
          style: TextStyle(
            fontFamily: 'Inter',
            fontSize: 12,
            color: Colors.white.withOpacity(0.65),
          ),
        ),
        const SizedBox(width: 8),
        Expanded(
          child: Text(
            value,
            textAlign: TextAlign.end,
            style: TextStyle(
              fontFamily: isHighlight ? 'Poppins' : 'Inter',
              fontWeight: isHighlight ? FontWeight.bold : FontWeight.w600,
              fontSize: isHighlight ? 15 : 13,
              color: isHighlight ? (goldAccent ?? const Color(0xFFD4AF37)) : Colors.white,
            ),
          ),
        ),
      ],
    );
  }

  Widget _buildLabel(String text) {
    return Padding(
      padding: const EdgeInsets.only(bottom: 6.0),
      child: Text(
        text,
        style: TextStyle(
          fontFamily: 'Inter',
          fontSize: 12,
          fontWeight: FontWeight.w600,
          color: Colors.white.withOpacity(0.9),
        ),
      ),
    );
  }

  InputDecoration _inputDecoration({
    required String hint,
    required IconData icon,
    required Color silverBorder,
    Widget? suffix,
    String? helper,
  }) {
    return InputDecoration(
      hintText: hint,
      helperText: helper,
      helperStyle: TextStyle(color: Colors.white.withOpacity(0.5), fontSize: 11),
      hintStyle: TextStyle(color: Colors.white.withOpacity(0.35), fontSize: 13),
      prefixIcon: Icon(icon, color: Colors.white70, size: 20),
      suffixIcon: suffix,
      filled: true,
      fillColor: Colors.black.withOpacity(0.25),
      contentPadding: const EdgeInsets.symmetric(horizontal: 16, vertical: 14),
      border: OutlineInputBorder(
        borderRadius: BorderRadius.circular(14),
        borderSide: BorderSide(color: silverBorder.withOpacity(0.3)),
      ),
      enabledBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(14),
        borderSide: BorderSide(color: silverBorder.withOpacity(0.3)),
      ),
      focusedBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(14),
        borderSide: const BorderSide(color: Color(0xFFD4AF37), width: 1.5),
      ),
      errorBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(14),
        borderSide: const BorderSide(color: Color(0xFFDC2626), width: 1.2),
      ),
      focusedErrorBorder: OutlineInputBorder(
        borderRadius: BorderRadius.circular(14),
        borderSide: const BorderSide(color: Color(0xFFDC2626), width: 1.5),
      ),
      errorStyle: const TextStyle(color: Color(0xFFFCA5A5), fontSize: 11),
    );
  }
}
